//! Chart playground: every `viz` diagram drawn once from synthetic data, on one page.
//!
//! The point is to look at the real renderer, not a mockup: the page is assembled by
//! [`report::html`], so it carries the report's own stylesheet and [`viz::REVEAL_CSS`], and
//! every figure is a string returned by the same functions a report calls. Each figure prints
//! its measured markup size, because that is what a report page pays for.
//!
//! ```sh
//! cargo run -p airbug-bench --example viz_gallery
//! open target/viz-playground.html
//! ```
use airbug_bench::{analysis::Decision, report, viz};

/// One rendered figure plus what it costs and what to look at.
struct Demo {
    /// Renderer call and arguments, as a reader would type them.
    source: &'static str,
    html: String,
    /// Why the figure is here: the invariant or edge case it holds.
    shows: &'static str,
}

/// Figures that belong under one heading.
struct Section {
    title: &'static str,
    demos: Vec<Demo>,
}

fn section(title: &'static str, demos: Vec<Demo>) -> Section {
    Section { title, demos }
}

fn main() -> airbug_bench::Result<()> {
    let path = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "target/viz-playground.html".into());
    let sections = [
        scatter_section(),
        effect_section(),
        distribution_section(),
        heat_section(),
        diagram_section(),
        edge_section(),
    ];
    let demos: Vec<&Demo> = sections.iter().flat_map(|s| &s.demos).collect();
    let total: usize = demos.iter().map(|d| d.html.len()).sum();

    let mut content = header(total, &demos);
    content.push_str(&controls());
    for (n, s) in sections.iter().enumerate() {
        content.push_str(&format!(
            "<section class=\"pg-group\"><h2>{} — {} ({} figures)</h2>",
            n + 1,
            s.title,
            s.demos.len()
        ));
        for d in &s.demos {
            content.push_str(&render(d));
        }
        content.push_str("</section>");
    }
    let page = report::html("")
        .replace("<!--DETAILS-->", "")
        .replace("<!--CHARTS-->", &content);
    if let Some(parent) = std::path::Path::new(&path).parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&path, &page)?;
    println!("figures: {}", demos.len());
    println!("chart markup: {total} bytes");
    println!("reveal css: {} bytes", viz::REVEAL_CSS.len());
    println!("page: {} bytes -> {path}", page.len());
    Ok(())
}

/// One demo as markup, with its measured size.
fn render(d: &Demo) -> String {
    let source = report::html_fragment(&format!("`{}`", d.source))
        .replace("<p>", "")
        .replace("</p>", "");
    format!(
        "<article class=\"pg\"><div class=\"pg-meta\"><code>{source}</code><strong>{} B</strong><span>{}</span></div>{}</article>",
        d.html.len(),
        d.shows,
        d.html,
    )
}

fn header(total: usize, demos: &[&Demo]) -> String {
    let widest = demos
        .iter()
        .map(|d| (d.source, d.html.len()))
        .max_by_key(|(_, len)| *len)
        .unwrap_or(("", 0));
    format!(
        "<section class=\"pg pg-summary\"><h2>Costs</h2>\
         <p>{count} figures drawn by <code>airbug_bench::viz</code>, {total} bytes of markup in \
         total, {} bytes per figure on average. The largest is <code>{widest_source}</code> at \
         {widest_len} B. Motion costs the page one stylesheet of {css} bytes plus roughly \
         {per} bytes per reveal group — the marks themselves are identical to a static render.</p>\
         <p>Every label goes through <code>viz::esc</code> and coordinates are fixed-point, so the \
         figures below are the same strings a report embeds. Nothing on this page is a mockup: each \
         block is generated by the function named above it. Two motions are in use: lines and \
         bars draw themselves along their own length, everything else is a staggered fade. Reload \
         to replay a build; print to get the final frame.</p></section>",
        total / demos.len().max(1),
        count = demos.len(),
        widest_source = widest.0,
        widest_len = widest.1,
        css = viz::REVEAL_CSS.len(),
        per = "<g class=\"rv\" style=\"--s:60ms\">".len(),
    )
}

/// Motion controls. Pure CSS over the classes the figures already carry: the renderer never
/// learns that a playground exists.
fn controls() -> String {
    format!(
        "<nav class=\"pg-controls\"><span>reveal</span>\
         <label><input type=\"checkbox\" id=\"still\"> final frame (as print / reduced-motion)</label>\
         <label><input type=\"checkbox\" id=\"pause\"> pause</label>\
         <label><input type=\"checkbox\" id=\"slow\"> slow ×3</label>\
         <label><input type=\"checkbox\" id=\"flat\"> no stagger</label>\
         <label><input type=\"checkbox\" id=\"nodraw\"> fade instead of draw</label>\
         <label><input type=\"checkbox\" id=\"notes\"> hide caveats</label>\
         <a href=\".\">replay</a></nav><style>{CSS}</style>"
    )
}

