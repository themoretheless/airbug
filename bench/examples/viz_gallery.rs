fn verdict(point: f64) -> Decision {
    if point > 5. {
        Decision::Regression
    } else if point < -5. {
        Decision::Improvement
    } else if point.abs() > 2.5 {
        Decision::Inconclusive
    } else {
        Decision::WithinMargin
    }
}
